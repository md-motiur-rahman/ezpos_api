import { query } from '../../db/pool.js';
import { buildUpdateSet } from '../../utils/sql.js';

const ORDER_COLUMNS = `id, shop_id, type, table_number, customer_name, status,
                       created_by_actor_type, created_by_actor_id, created_at, updated_at,
                       discount_type, discount_value, discount_reason,
                       discounted_by_actor_type, discounted_by_actor_id, discounted_at,
                       cancelled_at, cancelled_by_actor_type, cancelled_by_actor_id,
                       cancellation_reason, was_prepped`;

const ORDER_ITEM_DISCOUNT_COLUMNS = `discount_type, discount_value, discount_reason,
                       discounted_by_actor_type, discounted_by_actor_id, discounted_at`;

const ORDER_ITEM_VOID_COLUMNS = `voided_at, voided_by_actor_type, voided_by_actor_id,
                       void_reason, was_prepped`;

export async function createOrder(
  shopId,
  { type, tableNumber, customerName, createdByActorType, createdByActorId }
) {
  const { rows } = await query(
    `INSERT INTO orders
       (shop_id, type, table_number, customer_name, created_by_actor_type, created_by_actor_id)
     VALUES ($1, $2, $3, $4, $5, $6)
     RETURNING ${ORDER_COLUMNS}`,
    [shopId, type, tableNumber ?? null, customerName ?? null, createdByActorType, createdByActorId]
  );
  return rows[0];
}

/**
 * Bulk insert via unnest() - one atomic statement for every line,
 * regardless of how many, same discipline as every other multi-line
 * entity in this project (7.5/7.6/7.7). `ids` are pre-generated by the
 * caller (crypto.randomUUID()) rather than left to the DB default -
 * verified empirically before relying on it (explicit ids land correctly
 * in a bulk unnest() insert). This sidesteps needing to trust that
 * RETURNING's row order matches the SELECT/unnest's input order, which was
 * never actually verified and isn't needed now: order_item_modifiers below
 * needs each line's own id BEFORE it can be inserted, and pre-generating
 * gives that for free with no correlation risk.
 */
export async function createOrderItems(orderId, items) {
  const ids = items.map((item) => item.id);
  const menuItemIds = items.map((item) => item.menuItemId ?? null);
  const shopMenuItemIds = items.map((item) => item.shopMenuItemId ?? null);
  const variantIds = items.map((item) => item.variantId ?? null);
  const quantities = items.map((item) => item.quantity);
  const unitPrices = items.map((item) => item.unitPrice);

  await query(
    `INSERT INTO order_items
       (id, order_id, menu_item_id, shop_menu_item_id, variant_id, quantity, unit_price)
     SELECT unnest($1::uuid[]), $2, unnest($3::uuid[]), unnest($4::uuid[]),
            unnest($5::uuid[]), unnest($6::int[]), unnest($7::numeric[])`,
    [ids, orderId, menuItemIds, shopMenuItemIds, variantIds, quantities, unitPrices]
  );
}

/**
 * Same bulk pattern, across ALL lines' modifiers in one statement rather
 * than one insert per line. Verified empirically that an empty array here
 * (an order with no modifiers selected anywhere) is a safe no-op, not an
 * error - the caller skips calling this at all when there's nothing to
 * insert, but the query itself is safe either way.
 */
export async function createOrderItemModifiers(modifiers) {
  if (modifiers.length === 0) {
    return;
  }
  const orderItemIds = modifiers.map((m) => m.orderItemId);
  const modifierOptionIds = modifiers.map((m) => m.modifierOptionId);
  const priceDeltas = modifiers.map((m) => m.priceDelta);

  await query(
    `INSERT INTO order_item_modifiers (order_item_id, modifier_option_id, price_delta)
     SELECT unnest($1::uuid[]), unnest($2::uuid[]), unnest($3::numeric[])`,
    [orderItemIds, modifierOptionIds, priceDeltas]
  );
}

/** item_count via LEFT JOIN + count, same shape as listWastageLogsForShop (7.7). */
export async function listOrdersForShop(shopId) {
  const { rows } = await query(
    `SELECT o.id, o.shop_id, o.type, o.table_number, o.customer_name, o.status,
            o.created_by_actor_type, o.created_by_actor_id, o.created_at, o.updated_at,
            count(oi.id)::int AS item_count
     FROM orders o
     LEFT JOIN order_items oi ON oi.order_id = o.id
     WHERE o.shop_id = $1
     GROUP BY o.id
     ORDER BY o.created_at DESC`,
    [shopId]
  );
  return rows;
}

export async function findOrderByIdForShop(id, shopId) {
  const { rows } = await query(
    `SELECT ${ORDER_COLUMNS} FROM orders WHERE id = $1 AND shop_id = $2`,
    [id, shopId]
  );
  return rows[0] ?? null;
}

/**
 * Item name is JOINED live from menu_items/shop_menu_items, NOT
 * snapshotted - same precedent as listItemsForWastageLog (7.7): only PRICE
 * is historical/charged data worth freezing, a display name is not, and
 * soft-delete (not hard-delete) keeps the referenced row available
 * forever for this join to still work.
 */
export async function listItemsForOrder(orderId) {
  const { rows } = await query(
    `SELECT oi.id, oi.order_id, oi.menu_item_id, oi.shop_menu_item_id, oi.variant_id,
            oi.quantity, oi.unit_price, oi.created_at,
            oi.discount_type, oi.discount_value, oi.discount_reason,
            oi.discounted_by_actor_type, oi.discounted_by_actor_id, oi.discounted_at,
            oi.voided_at, oi.voided_by_actor_type, oi.voided_by_actor_id,
            oi.void_reason, oi.was_prepped,
            COALESCE(mi.name, smi.name) AS item_name,
            miv.name AS variant_name
     FROM order_items oi
     LEFT JOIN menu_items mi ON mi.id = oi.menu_item_id
     LEFT JOIN shop_menu_items smi ON smi.id = oi.shop_menu_item_id
     LEFT JOIN menu_item_variants miv ON miv.id = oi.variant_id
     WHERE oi.order_id = $1
     ORDER BY oi.created_at`,
    [orderId]
  );
  return rows;
}

/**
 * Sets or clears the order-level discount (9.3). Passing null discountType
 * clears every discount column together (including the actor/timestamp
 * audit fields) - same "explicit null clears" contract used for the input,
 * carried straight through to storage.
 */
export async function setOrderDiscount(
  orderId,
  { discountType, discountValue, reason, actorType, actorId }
) {
  const { rows } = await query(
    `UPDATE orders
     SET discount_type = $2, discount_value = $3, discount_reason = $4,
         discounted_by_actor_type = $5, discounted_by_actor_id = $6,
         discounted_at = CASE WHEN $2::text IS NULL THEN NULL ELSE now() END,
         updated_at = now()
     WHERE id = $1
     RETURNING ${ORDER_COLUMNS}`,
    [orderId, discountType, discountValue, reason ?? null, actorType, actorId]
  );
  return rows[0];
}

/** Scoped to order_id as well as id, so a caller can never discount/void an item belonging to a different order via a stale/foreign orderItemId. */
export async function findOrderItemForOrder(orderItemId, orderId) {
  const { rows } = await query(
    `SELECT id, order_id, quantity, unit_price, ${ORDER_ITEM_DISCOUNT_COLUMNS}, ${ORDER_ITEM_VOID_COLUMNS}
     FROM order_items WHERE id = $1 AND order_id = $2`,
    [orderItemId, orderId]
  );
  return rows[0] ?? null;
}

